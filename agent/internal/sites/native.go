package sites

// Native engine (NATIVE-01, owner decision NATIVE-1 2026-11-16): a website served by the host's Nginx and its own
// PHP-FPM from the ondrej/php PPA (8.1-8.5), with its database on the host's MariaDB over the unix socket. Only
// WordPress, plain PHP and static websites; Docker stays the default engine.
//
// Isolation per website, in place of a container:
//   - its own Linux user np-<id> (no shell, no password); its files belong to it, the host's Nginx (www-data) reads
//     them through the website's group;
//   - its own PHP-FPM master as a systemd service running as that user (never root), with the systemd sandbox:
//     read-only system, only its own folder writable, private /tmp, no access to the agent, Docker or other
//     websites, no private or loopback addresses (the internet stays reachable), and memory, CPU and task limits;
//   - open_basedir to its folder, process functions disabled, its own sessions and uploads folder.
//
// Traefik keeps ports 80/443 and the certificates: the agent writes a file-provider entry per native website that
// sends its hosts to the host's Nginx on the edge network's gateway address.

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"path/filepath"
	"strings"

	"github.com/thuekx/docker-panel-VPS/agent/internal/spec"
)

// Engines a website can run on.
const (
	EngineDocker = ""       // one Docker stack per website (default, every website made before v1.18.0)
	EngineNative = "native" // host Nginx + PHP-FPM + MariaDB
)

// NativePort is the port the host's Nginx listens on, on the edge network's gateway address only.
const NativePort = 8088

// Native limits per website (the counterpart of the containers' mem_limit and pids_limit).
const (
	NativeMemory   = "512M"
	NativeCPU      = "100%"
	NativeTasks    = 256
	NativeChildren = 8
)

// IsNative is true for a website on the native engine.
func (s Site) IsNative() bool { return s.Engine == EngineNative }

// NativeUser is the Linux user of a native website: np-<id>, shortened with a hash past 32 characters.
func NativeUser(id string) string {
	u := "np-" + id
	if len(u) <= 32 {
		return u
	}
	h := sha256.Sum256([]byte(id))
	return "np-" + strings.TrimRight(id[:20], "-") + "-" + hex.EncodeToString(h[:])[:6]
}

// NativeUnit is the systemd service of a native website's PHP-FPM.
func NativeUnit(id string) string { return "nostek-php-" + id + ".service" }

// NativePaths are where the native engine's files live (tests point them into a temporary folder).
type NativePaths struct {
	Etc  string // /etc
	Run  string // /run
	Data string // /srv/nostek
}

func (p NativePaths) fpmConf(id string) string {
	return filepath.Join(p.Etc, "nostek", "native", id, "php-fpm.conf")
}
func (p NativePaths) unit(id string) string {
	return filepath.Join(p.Etc, "systemd", "system", NativeUnit(id))
}
func (p NativePaths) nginx(id string) string {
	return filepath.Join(p.Etc, "nginx", "nostek", id+".conf")
}
func (p NativePaths) edge(id string) string {
	return filepath.Join(p.Data, "edge", "dynamic", "site-"+id+".yml")
}
func (p NativePaths) socket(id string) string {
	return filepath.Join(p.Run, "nostek-php", id, "php.sock")
}
func (p NativePaths) site(id string) string { return filepath.Join(p.Data, "sites", id) }

// NativeDocroot is the folder Nginx serves: the website's wp/ folder, as in Docker.
func (p NativePaths) docroot(id string) string { return filepath.Join(p.site(id), "wp") }

// nativePHP is true when the website runs PHP (WordPress or plain PHP); a static website has only Nginx.
func (s Site) nativePHP() bool { return s.AppName() != spec.AppStatic }

// disabledFunctions are refused to website PHP: no processes, no changing the PHP process itself.
const disabledFunctions = "exec,passthru,shell_exec,system,proc_open,popen,pcntl_exec,pcntl_fork,dl,putenv"

