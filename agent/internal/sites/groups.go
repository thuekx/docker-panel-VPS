package sites

// GRP-01: website groups. A group is a systemd slice with limits for all its websites together: CPU, memory and
// the number of processes. A website in a group runs its containers (Docker: cgroup_parent) or its PHP-FPM service
// and WP-CLI runs (native: Slice=) inside that slice, so the websites of a group share its limits and cannot take
// more than the group has. A website's own limits (RES-01) stay as they are, inside the group's. Without groups
// nothing changes: every website runs as before.

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"runtime"
	"sort"
	"strconv"
	"strings"
)

// GroupLimits are the limits of one group, for all its websites together.
type GroupLimits struct {
	CPU    int `json:"cpu_percent"` // 100 = one CPU core
	Memory int `json:"memory_mb"`
	Tasks  int `json:"tasks"` // processes and threads
}

// Group is a group with its limits, its websites and what it uses now.
type Group struct {
	Name string `json:"name"`
	GroupLimits
	Sites   []string `json:"sites"`
	MemUsed int      `json:"memory_used_mb"` // -1 when unknown
}

var groupNameRe = regexp.MustCompile(`^[a-z0-9]{1,24}$`)

// Bounds of the limits: at least enough for one small website, at most the server.
const (
	GroupMinCPU    = 10
	GroupMinMemory = 128
	GroupMinTasks  = 64
	GroupMaxTasks  = 65536
)

// GroupSlice is the systemd slice of a group (systemd puts it inside npgroup.slice).
func GroupSlice(name string) string { return "npgroup-" + name + ".slice" }

func (m *Manager) groupsFile() string { return filepath.Join(m.cfg.Data, "groups.json") }

func (m *Manager) unitDir() string {
	if m.srvEtc != "" {
		return filepath.Join(m.srvEtc, "systemd", "system")
	}
	return "/etc/systemd/system"
}

func (m *Manager) cgroupRoot() string {
	if m.cgroupFS != "" {
		return m.cgroupFS
	}
	return "/sys/fs/cgroup"
}

func (m *Manager) cpus() int {
	if m.cpuFn != nil {
		return m.cpuFn()
	}
	return runtime.NumCPU()
}

func (m *Manager) readGroups() (map[string]GroupLimits, error) {
	g := map[string]GroupLimits{}
	b, err := os.ReadFile(m.groupsFile())
	if errors.Is(err, os.ErrNotExist) {
		return g, nil
	}
	if err != nil {
		return nil, err
	}
	if err := json.Unmarshal(b, &g); err != nil {
		return nil, fmt.Errorf("groups.json: %w", err)
	}
	return g, nil
}

func (m *Manager) writeGroups(g map[string]GroupLimits) error {
	b, _ := json.MarshalIndent(g, "", "  ")
	return writeFile(m.groupsFile(), append(b, '\n'), 0o644)
}

// checkGroup refuses a bad name or limits outside the bounds.
func (m *Manager) checkGroup(name string, l GroupLimits) error {
	if !groupNameRe.MatchString(name) {
		return fmt.Errorf("%w: a group name is 1-24 of a-z0-9", ErrBadInput)
	}
	if maxCPU := m.cpus() * 100; l.CPU < GroupMinCPU || l.CPU > maxCPU {
		return fmt.Errorf("%w: cpu_percent must be %d-%d (100 = one core, this server has %d)", ErrBadInput, GroupMinCPU, maxCPU, m.cpus())
	}
	if maxMem := m.memMB(); l.Memory < GroupMinMemory || (maxMem > 0 && l.Memory > maxMem) {
		return fmt.Errorf("%w: memory_mb must be %d-%d", ErrBadInput, GroupMinMemory, maxMem)
	}
	if l.Tasks < GroupMinTasks || l.Tasks > GroupMaxTasks {
		return fmt.Errorf("%w: tasks must be %d-%d", ErrBadInput, GroupMinTasks, GroupMaxTasks)
	}
	return nil
}

// sliceProps are the systemd properties of a group's slice.
func sliceProps(l GroupLimits) []string {
	return []string{
		fmt.Sprintf("CPUQuota=%d%%", l.CPU),
		fmt.Sprintf("MemoryMax=%dM", l.Memory),
		"MemorySwapMax=0",
		fmt.Sprintf("TasksMax=%d", l.Tasks),
	}
}

// SliceUnit renders the slice unit of a group.
func SliceUnit(name string, l GroupLimits) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by nostek-agent for website group %s. Do not edit: the agent rewrites it.\n[Unit]\nDescription=Nostek website group %s\n\n[Slice]\n", name, name)
	for _, p := range sliceProps(l) {
		b.WriteString(p + "\n")
	}
	return b.String()
}

// Groups lists the groups with their websites and memory in use.
func (m *Manager) Groups() ([]Group, error) {
	g, err := m.readGroups()
	if err != nil {
		return nil, err
	}
	list, err := m.List()
	if err != nil {
		return nil, err
	}
	members := map[string][]string{}
	for _, s := range list {
		if s.Group != "" {
			members[s.Group] = append(members[s.Group], s.ID)
		}
	}
	out := make([]Group, 0, len(g))
	for name, l := range g {
		sites := members[name]
		if sites == nil {
			sites = []string{}
		}
		sort.Strings(sites)
		out = append(out, Group{Name: name, GroupLimits: l, Sites: sites, MemUsed: m.groupMem(name)})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

// groupMem is the memory a group's slice uses now in MB (-1 when unknown, e.g. nothing runs in it yet).
func (m *Manager) groupMem(name string) int {
	b, err := os.ReadFile(filepath.Join(m.cgroupRoot(), "npgroup.slice", GroupSlice(name), "memory.current"))
	if err != nil {
		return -1
	}
	n, err := strconv.ParseInt(strings.TrimSpace(string(b)), 10, 64)
	if err != nil {
		return -1
	}
	return int(n >> 20)
}

// SetGroup makes a group or changes its limits; the new limits apply at once to the websites running in it.
func (m *Manager) SetGroup(ctx context.Context, name string, l GroupLimits) error {
	if err := m.checkGroup(name, l); err != nil {
		return err
	}
	if m.fw == nil {
		return errors.New("this agent cannot run systemctl")
	}
	if !m.mu.TryLock() {
		return ErrBusy
	}
	defer m.mu.Unlock()
	g, err := m.readGroups()
	if err != nil {
		return err
	}
	unit := filepath.Join(m.unitDir(), GroupSlice(name))
	prev, hadPrev := g[name]
	if err := os.MkdirAll(m.unitDir(), 0o755); err != nil {
		return err
	}
	if err := writeFile(unit, []byte(SliceUnit(name, l)), 0o644); err != nil {
		return err
	}
	undo := func() {
		if hadPrev {
			_ = writeFile(unit, []byte(SliceUnit(name, prev)), 0o644)
		} else {
			_ = os.Remove(unit)
		}
		_, _ = m.fw.Host(ctx, nil, "systemctl", "daemon-reload")
	}
	if out, err := m.fw.Host(ctx, nil, "systemctl", "daemon-reload"); err != nil {
		undo()
		return fmt.Errorf("systemctl daemon-reload: %s", tail(out))
	}
	// a slice that already runs websites takes its new limits now (the unit file keeps them after a reboot)
	args := append([]string{"set-property", "--runtime", GroupSlice(name)}, sliceProps(l)...)
	if out, err := m.fw.Host(ctx, nil, "systemctl", args...); err != nil {
		undo()
		return fmt.Errorf("systemctl set-property: %s", tail(out))
	}
	if out, err := m.fw.Host(ctx, nil, "systemctl", "start", GroupSlice(name)); err != nil {
		undo()
		return fmt.Errorf("systemctl start: %s", tail(out))
	}
	g[name] = l
	return m.writeGroups(g)
}

// DeleteGroup removes a group that has no website.
func (m *Manager) DeleteGroup(ctx context.Context, name string) error {
	if !groupNameRe.MatchString(name) {
		return ErrNotFound
	}
	if !m.mu.TryLock() {
		return ErrBusy
	}
	defer m.mu.Unlock()
	g, err := m.readGroups()
	if err != nil {
		return err
	}
	if _, ok := g[name]; !ok {
		return ErrNotFound
	}
	if m.fw == nil {
		return errors.New("this agent cannot run systemctl")
	}
	list, err := m.List()
	if err != nil {
		return err
	}
	for _, s := range list {
		if s.Group == name {
			return fmt.Errorf("%w: website %s is still in group %s", ErrBadInput, s.ID, name)
		}
	}
	delete(g, name)
	if err := m.writeGroups(g); err != nil {
		return err
	}
	if err := os.Remove(filepath.Join(m.unitDir(), GroupSlice(name))); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	_, _ = m.fw.Host(ctx, nil, "systemctl", "daemon-reload")
	return nil
}

// SetSiteGroup moves a website into a group ("" = out of every group) and restarts it there.
func (m *Manager) SetSiteGroup(ctx context.Context, id, group string) error {
	s, err := m.readySite(id)
	if err != nil {
		return err
	}
	if group != "" {
		g, err := m.readGroups()
		if err != nil {
			return err
		}
		if _, ok := g[group]; !ok {
			return fmt.Errorf("%w: there is no group %q", ErrBadInput, group)
		}
	}
	if s.Group == group {
		return nil
	}
	if !m.mu.TryLock() {
		return ErrBusy
	}
	defer m.mu.Unlock()
	next := s
	next.Group = group
	return m.writeLimits(ctx, next)
}

var cgroupLine = regexp.MustCompile(`^    cgroup_parent: `)

// applyGroup puts every service of a rendered compose file into the website's group (as the service's first key).
func applyGroup(cf, group string) string {
	if group == "" {
		return cf
	}
	lines := strings.Split(cf, "\n")
	first, seen := map[int]bool{}, map[string]bool{}
	eachService(cf, func(i int, svc, _ string) {
		if !seen[svc] {
			seen[svc], first[i] = true, true
		}
	})
	out := make([]string, 0, len(lines)+len(seen))
	for i, l := range lines {
		if cgroupLine.MatchString(l) {
			continue
		}
		if first[i] {
			out = append(out, "    cgroup_parent: "+GroupSlice(group))
		}
		out = append(out, l)
	}
	return strings.Join(out, "\n")
}
