package sites

// Web application firewall (SEC-01 wave 3b), like cPanel's ModSecurity page. The WAF is the core stack's `waf`
// container (Coraza with the OWASP Core Rule Set, from the panel image). While a website's WAF is on, every router
// of the website sends its visits to that container instead of the website, and the container passes them on to
// the website after the rules. The agent writes two files per website: the edge's service entry
// (<data>/edge/dynamic/waf-<id>.yml) and the website's rules (<data>/edge/waf/<id>.json). Off by default.

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"time"

	"github.com/thuekx/docker-panel-VPS/agent/internal/catalog"
)

const (
	wafContainer   = "nostek-core-waf-1"
	wafURL         = "http://" + wafContainer + ":8090"
	MaxWAFExclude  = 50
	MaxWAFSkip     = 20
	wafEventsKept  = 100
	wafEventsShown = 50
)

// WAF is a website's firewall setting.
type WAF struct {
	Mode     string   `json:"mode"`     // detect | block
	Paranoia int      `json:"paranoia"` // 1 standard, 2 stricter
	Exclude  []int    `json:"exclude,omitempty"`
	Skip     []string `json:"skip,omitempty"`
}

var wafSkipRe = regexp.MustCompile(`^/[A-Za-z0-9._~/-]{0,200}$`)

// wafRuleOK is a rule that may be switched off: a CRS rule that finds something, not one that only counts or decides.
func wafRuleOK(id int) bool {
	return id >= 911000 && id <= 999999 && !(id >= 949000 && id < 950000) && !(id >= 959000)
}

// wafService is the edge service the website's routers use: the WAF while it is on, else the website itself.
func (s Site) wafService(docker bool) string {
	rid := "site-" + s.ID
	if s.WAF == nil {
		return rid
	}
	if docker {
		return rid + "-waf@file"
	}
	return rid + "-waf"
}

// upstream is where the WAF passes a website's visits on.
func (m *Manager) wafUpstream(s Site) string {
	if s.IsNative() && m.native != nil {
		return fmt.Sprintf("http://%s:%d", m.native.Gateway, NativePort)
	}
	svc, port := "web", 80
	if s.IsRuntime() {
		svc, port = "app", NodePort
	}
	if r, ok := catalog.Ready(s.AppName()); ok {
		svc, port = "app", r.Port
	}
	return fmt.Sprintf("http://%s-%s-1:%d", Project(s.ID), svc, port)
}

func (m *Manager) wafEdgeFile(id string) string {
	return filepath.Join(m.cfg.Data, "edge", "dynamic", "waf-"+id+".yml")
}
func (m *Manager) wafRulesFile(id string) string {
	return filepath.Join(m.cfg.Data, "edge", "waf", id+".json")
}

type wafRules struct {
	Site     string   `json:"site"`
	Hosts    []string `json:"hosts"`
	Upstream string   `json:"upstream"`
	Mode     string   `json:"mode"`
	Paranoia int      `json:"paranoia"`
	Exclude  []int    `json:"exclude"`
	Skip     []string `json:"skip"`
}

// writeWAF writes a website's WAF files when its WAF is on (the rules first, so the WAF knows the website before
// the edge sends it a visit).
func (m *Manager) writeWAF(s Site) error {
	if s.WAF == nil {
		return nil
	}
	var hosts []string
	for _, h := range s.Hosts {
		if h.Routed {
			hosts = append(hosts, h.Name)
		}
	}
	if len(hosts) == 0 {
		return nil
	}
	r := wafRules{Site: s.ID, Hosts: hosts, Upstream: m.wafUpstream(s), Mode: s.WAF.Mode, Paranoia: s.WAF.Paranoia,
		Exclude: s.WAF.Exclude, Skip: s.WAF.Skip}
	if r.Exclude == nil {
		r.Exclude = []int{}
	}
	if r.Skip == nil {
		r.Skip = []string{}
	}
	b, _ := json.MarshalIndent(r, "", "  ")
	for _, d := range []string{filepath.Dir(m.wafRulesFile(s.ID)), filepath.Dir(m.wafEdgeFile(s.ID))} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			return err
		}
	}
	if err := writeFile(m.wafRulesFile(s.ID), b, 0o644); err != nil {
		return err
	}
	edge := fmt.Sprintf("# Generated by nostek-agent for site %s (WAF on). Do not edit: the agent rewrites it.\nhttp:\n  services:\n"+
		"    site-%s-waf:\n      loadBalancer:\n        passHostHeader: true\n        servers:\n          - url: %q\n", s.ID, s.ID, wafURL)
	return writeFile(m.wafEdgeFile(s.ID), []byte(edge), 0o644)
}

// dropWAF removes a website's WAF files (after its routers no longer use them).
func (m *Manager) dropWAF(id string) {
	for _, f := range []string{m.wafEdgeFile(id), m.wafRulesFile(id)} {
		if err := os.Remove(f); err != nil && !errors.Is(err, fs.ErrNotExist) {
			_ = err
		}
	}
}

// SyncWAF writes the WAF files of every website whose WAF is on and removes the others (agent start).
func (m *Manager) SyncWAF() error {
	list, err := m.List()
	if err != nil {
		return err
	}
	on := map[string]bool{}
	var errs []string
	for _, s := range list {
		if s.WAF != nil {
			on[s.ID] = true
			if err := m.writeWAF(s); err != nil {
				errs = append(errs, s.ID+": "+err.Error())
			}
		}
	}
	ents, _ := os.ReadDir(filepath.Dir(m.wafRulesFile("x")))
	for _, e := range ents {
		if id, ok := strings.CutSuffix(e.Name(), ".json"); ok && !on[id] {
			m.dropWAF(id)
		}
	}
	if len(errs) > 0 {
		return errors.New(strings.Join(errs, "; "))
	}
	return nil
}

// wafReady is true when the core stack's WAF container runs and answers its health check.
func (m *Manager) wafReady(ctx context.Context) bool {
	ctx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()
	out, err := m.run.Docker(ctx, m.cfg.Data, nil, "inspect", "--format", "{{.State.Status}} {{if .State.Health}}{{.State.Health.Status}}{{end}}", wafContainer)
	return err == nil && strings.TrimSpace(string(out)) == "running healthy"
}

// nextWAF applies a WAF change to next; ok is false for a change that is not about the WAF.
func (m *Manager) nextWAF(s Site, next *Site, c SecurityChange) (bool, error) {
	if !strings.HasPrefix(c.Op, "waf-") {
		return false, nil
	}
	cur := s.WAF
	if c.Op != "waf-set" && cur == nil {
		return true, fmt.Errorf("%w: the firewall is off", ErrBadInput)
	}
	w := WAF{}
	if cur != nil {
		w = WAF{Mode: cur.Mode, Paranoia: cur.Paranoia, Exclude: slices.Clone(cur.Exclude), Skip: slices.Clone(cur.Skip)}
	}
	switch c.Op {
	case "waf-set":
		if c.Mode != "detect" && c.Mode != "block" {
			return true, fmt.Errorf("%w: the mode is detect or block", ErrBadInput)
		}
		if c.Level < 1 || c.Level > 2 {
			return true, fmt.Errorf("%w: the paranoia level is 1 or 2", ErrBadInput)
		}
		if cur != nil && cur.Mode == c.Mode && cur.Paranoia == c.Level {
			return true, ErrNoChange
		}
		if cur == nil && !m.wafReady(context.Background()) {
			return true, fmt.Errorf("%w: the firewall service is not running yet; update the panel first (PANEL-01 UPDATE)", ErrBadInput)
		}
		w.Mode, w.Paranoia = c.Mode, c.Level
	case "waf-off":
		next.WAF = nil
		return true, nil
	case "waf-exclude-add":
		if !wafRuleOK(c.Rule) {
			return true, fmt.Errorf("%w: %d is not a rule that can be switched off (911000-999999, not the scoring rules)", ErrBadInput, c.Rule)
		}
		if slices.Contains(w.Exclude, c.Rule) {
			return true, ErrNoChange
		}
		if len(w.Exclude) >= MaxWAFExclude {
			return true, fmt.Errorf("%w: at most %d rules switched off", ErrBadInput, MaxWAFExclude)
		}
		w.Exclude = append(w.Exclude, c.Rule)
		slices.Sort(w.Exclude)
	case "waf-exclude-remove":
		i := slices.Index(w.Exclude, c.Rule)
		if i < 0 {
			return true, fmt.Errorf("%w: rule %d is not switched off", ErrBadInput, c.Rule)
		}
		w.Exclude = slices.Delete(w.Exclude, i, i+1)
	case "waf-skip-add":
		p := strings.TrimSpace(c.Path)
		if p == "/" || !wafSkipRe.MatchString(p) || strings.Contains(p, "..") || strings.Contains(p, "//") {
			return true, fmt.Errorf("%w: a path starts with / and uses letters, digits, . _ ~ - and / (not / alone: turn the firewall off instead)", ErrBadInput)
		}
		if slices.Contains(w.Skip, p) {
			return true, ErrNoChange
		}
		if len(w.Skip) >= MaxWAFSkip {
			return true, fmt.Errorf("%w: at most %d paths", ErrBadInput, MaxWAFSkip)
		}
		w.Skip = append(w.Skip, p)
		slices.Sort(w.Skip)
	case "waf-skip-remove":
		i := slices.Index(w.Skip, c.Path)
		if i < 0 {
			return true, fmt.Errorf("%w: %s is checked already", ErrBadInput, c.Path)
		}
		w.Skip = slices.Delete(w.Skip, i, i+1)
	default:
		return true, fmt.Errorf("%w: unknown change", ErrBadInput)
	}
	if len(w.Exclude) == 0 {
		w.Exclude = nil
	}
	if len(w.Skip) == 0 {
		w.Skip = nil
	}
	next.WAF = &w
	return true, nil
}

// WAFEvent is one rule the WAF matched on a visit.
type WAFEvent struct {
	Time   int64  `json:"t"`
	Site   string `json:"site"`
	IP     string `json:"ip"`
	URI    string `json:"uri"`
	Rule   int    `json:"rule"`
	Msg    string `json:"msg"`
	Data   string `json:"data,omitempty"`
	Action string `json:"action"`
}

// WAFRuleCount is how often a rule matched in the kept events.
type WAFRuleCount struct {
	Rule     int    `json:"rule"`
	Msg      string `json:"msg"`
	Count    int    `json:"count"`
	Excluded bool   `json:"excluded"`
}

// WAFView is the firewall card of the Security page.
type WAFView struct {
	On       bool           `json:"on"`
	Mode     string         `json:"mode"`
	Paranoia int            `json:"paranoia"`
	Exclude  []int          `json:"exclude"`
	Skip     []string       `json:"skip"`
	Blocked  int            `json:"blocked"` // visits blocked, in the kept events
	Events   []WAFEvent     `json:"events"`
	Rules    []WAFRuleCount `json:"rules"`
}

// wafView returns a website's firewall setting and its latest events.
func (m *Manager) wafView(s Site) WAFView {
	v := WAFView{Exclude: []int{}, Skip: []string{}, Events: []WAFEvent{}, Rules: []WAFRuleCount{}}
	if s.WAF != nil {
		v.On, v.Mode, v.Paranoia = true, s.WAF.Mode, s.WAF.Paranoia
		if s.WAF.Exclude != nil {
			v.Exclude = s.WAF.Exclude
		}
		if s.WAF.Skip != nil {
			v.Skip = s.WAF.Skip
		}
	}
	ls := m.loginDB()
	ls.mu.Lock()
	ev := slices.Clone(ls.st.WAF[s.ID])
	ls.mu.Unlock()
	counts := map[int]*WAFRuleCount{}
	for i := len(ev) - 1; i >= 0; i-- { // newest first
		e := ev[i]
		if e.Action == "blocked" {
			v.Blocked++
		}
		if len(v.Events) < wafEventsShown {
			v.Events = append(v.Events, e)
		}
		if e.Rule == 949110 {
			continue
		}
		c := counts[e.Rule]
		if c == nil {
			c = &WAFRuleCount{Rule: e.Rule, Msg: e.Msg, Excluded: slices.Contains(v.Exclude, e.Rule)}
			counts[e.Rule] = c
		}
		c.Count++
	}
	for _, c := range counts {
		v.Rules = append(v.Rules, *c)
	}
	slices.SortFunc(v.Rules, func(a, b WAFRuleCount) int {
		if a.Count != b.Count {
			return b.Count - a.Count
		}
		return a.Rule - b.Rule
	})
	return v
}
