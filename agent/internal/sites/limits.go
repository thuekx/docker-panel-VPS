package sites

// Resource limits per website (RES-01, 2026-11-16 01:46 WIB). Every website starts on our standard: the
// container memory limits of the templates and the standard PHP settings. They can only be raised, from a
// short list, when a website needs more (and go back to the standard), never below it. Raising PHP's
// memory_limit raises the memory of the containers that run PHP with it, so memory_limit always has room.

import (
	"bufio"
	"context"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"time"
)

// RAMChoices are the container memory limits (MB) a service can be raised to.
var RAMChoices = []int{768, 1024, 1536, 2048}

// PHPSettings are the PHP settings that can be raised (like cPanel's MultiPHP INI Editor).
type PHPSettings struct {
	Memory    int `json:"memory_mb"`      // memory_limit
	Upload    int `json:"upload_mb"`      // upload_max_filesize and post_max_size
	ExecTime  int `json:"exec_seconds"`   // max_execution_time
	InputVars int `json:"max_input_vars"` // max_input_vars
}

// PHPStandard is our standard PHP setting of every website (the php.ini every website had before v1.18.0).
var PHPStandard = PHPSettings{Memory: 256, Upload: 128, ExecTime: 120, InputVars: 1000}

// PHPChoices are the values each PHP setting can take (the standard first).
var PHPChoices = map[string][]int{
	"memory_mb":      {256, 384, 512, 768, 1024},
	"upload_mb":      {128, 256, 512, 1024},
	"exec_seconds":   {120, 300, 600, 900},
	"max_input_vars": {1000, 3000, 5000, 10000},
}

// php returns the PHP settings of the website: the standard where nothing was raised.
func (s Site) php() PHPSettings {
	p := PHPStandard
	if s.PHPLimits == nil {
		return p
	}
	p.Memory = max(p.Memory, s.PHPLimits.Memory)
	p.Upload = max(p.Upload, s.PHPLimits.Upload)
	p.ExecTime = max(p.ExecTime, s.PHPLimits.ExecTime)
	p.InputVars = max(p.InputVars, s.PHPLimits.InputVars)
	return p
}

// PHPIniFile renders the website's php.ini; with the standard settings it is exactly PHPIni.
func (s Site) PHPIniFile() string {
	p := s.php()
	if p == PHPStandard {
		return PHPIni
	}
	return fmt.Sprintf(`; Generated by nostek-agent.
upload_max_filesize = %dM
post_max_size = %dM
memory_limit = %dM
max_execution_time = %d
max_input_vars = %d
expose_php = Off
`, p.Upload, p.Upload, p.Memory, p.ExecTime, p.InputVars)
}

var bodyLine = regexp.MustCompile(`client_max_body_size [0-9]+m;`)

// nginxBody makes a website's Nginx accept the upload size its PHP accepts.
func (s Site) nginxBody(conf string) string {
	return bodyLine.ReplaceAllString(conf, fmt.Sprintf("client_max_body_size %dm;", s.php().Upload))
}

var memLine = regexp.MustCompile(`^    mem_limit: ([0-9]+)m$`)

// eachService calls f with the service and line of every line inside the services of a rendered compose file.
func eachService(cf string, f func(i int, svc, line string)) {
	in, svc := false, ""
	for i, l := range strings.Split(cf, "\n") {
		switch {
		case l == "services:":
			in = true
		case l != "" && !strings.HasPrefix(l, " ") && !strings.HasPrefix(l, "#"):
			in = false
		case !in:
		case strings.HasPrefix(l, "  ") && !strings.HasPrefix(l, "   ") && strings.HasSuffix(l, ":"):
			svc = strings.TrimSuffix(strings.TrimSpace(l), ":")
		case svc != "":
			f(i, svc, l)
		}
	}
}

// ServiceRAM is the memory limit of one service of a website.
type ServiceRAM struct {
	Service  string `json:"service"`
	Standard int    `json:"standard_mb"`
	Current  int    `json:"current_mb"`
	PHP      bool   `json:"php,omitempty"` // this service runs the website's PHP
}

// serviceRAM reads the memory limit of every service of a rendered compose file, in file order.
func serviceRAM(cf string) []ServiceRAM {
	var out []ServiceRAM
	eachService(cf, func(_ int, svc, l string) {
		if m := memLine.FindStringSubmatch(l); m != nil {
			n, _ := strconv.Atoi(m[1])
			out = append(out, ServiceRAM{Service: svc, Standard: n, Current: n})
		}
	})
	return out
}

// applyRAM sets the raised memory limits of a website in its rendered compose file.
func applyRAM(cf string, ram map[string]int) string {
	if len(ram) == 0 {
		return cf
	}
	lines := strings.Split(cf, "\n")
	eachService(cf, func(i int, svc, l string) {
		if m := memLine.FindStringSubmatch(l); m != nil {
			std, _ := strconv.Atoi(m[1])
			if v, ok := ram[svc]; ok && v > std {
				lines[i] = fmt.Sprintf("    mem_limit: %dm", v)
			}
		}
	})
	return strings.Join(lines, "\n")
}

// phpServices are the services whose PHP reads php.ini (PHP-FPM, Apache, WP-CLI, Laravel's workers).
func phpServices(cf string) map[string]bool {
	out := map[string]bool{}
	eachService(cf, func(_ int, svc, l string) {
		if strings.HasPrefix(l, "      - ./php.ini:") {
			out[svc] = true
		}
	})
	return out
}

// ramFor is the smallest memory that leaves PHP's memory_limit room in its container (half again as much).
func ramFor(phpMB, current int) int {
	need := phpMB * 3 / 2
	if current >= need {
		return current
	}
	for _, c := range RAMChoices {
		if c >= need {
			return c
		}
	}
	return RAMChoices[len(RAMChoices)-1]
}

// Limits is what the panel shows on a website's Resources card.
type Limits struct {
	Services  []ServiceRAM     `json:"services"`
	RAMChoice []int            `json:"ram_choices"`
	PHP       *PHPSettings     `json:"php,omitempty"` // nil: the website has no PHP settings
	PHPStd    PHPSettings      `json:"php_standard"`
	PHPChoice map[string][]int `json:"php_choices"`
	HostMB    int              `json:"host_mb"`  // the server's memory
	TotalMB   int              `json:"total_mb"` // the memory limits of every website together
}

// LimitChange is a change of a website's limits; a service or setting set to the standard drops its raise.
type LimitChange struct {
	RAM map[string]int `json:"ram"`
	PHP *PHPSettings   `json:"php"`
}

func (m *Manager) memMB() int {
	if m.memFn != nil {
		return m.memFn()
	}
	f, err := os.Open("/proc/meminfo")
	if err != nil {
		return 0
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		if v, ok := strings.CutPrefix(sc.Text(), "MemTotal:"); ok {
			kb, _ := strconv.Atoi(strings.TrimSpace(strings.TrimSuffix(strings.TrimSpace(v), "kB")))
			return kb / 1024
		}
	}
	return 0
}

// limitsOf works out the limits of one website from its compose file as the templates render it.
func (s Site) limitsOf() ([]ServiceRAM, bool, error) {
	if s.IsNative() { // one PHP-FPM service; the host's Nginx and MariaDB are shared, not the website's
		if !s.nativePHP() {
			return nil, false, nil
		}
		return []ServiceRAM{{Service: "php", Standard: NativeMemory, Current: s.nativeMem(), PHP: true}}, true, nil
	}
	std := s
	std.RAM = nil
	cf, err := std.Compose()
	if err != nil {
		return nil, false, err
	}
	php := phpServices(cf)
	out := serviceRAM(cf)
	for i := range out {
		if v, ok := s.RAM[out[i].Service]; ok && v > out[i].Standard {
			out[i].Current = v
		}
		out[i].PHP = php[out[i].Service]
	}
	return out, len(php) > 0, nil
}

// Limits returns a website's limits, its choices, and the memory of the server and of all websites together.
func (m *Manager) Limits(id string) (Limits, error) {
	s, err := m.readySite(id)
	if err != nil {
		return Limits{}, err
	}
	svcs, hasPHP, err := s.limitsOf()
	if err != nil {
		return Limits{}, fmt.Errorf("%w: this agent no longer offers the version this website runs", ErrBadInput)
	}
	l := Limits{Services: svcs, RAMChoice: RAMChoices, PHPStd: PHPStandard, PHPChoice: PHPChoices, HostMB: m.memMB(), TotalMB: m.totalMB()}
	if hasPHP {
		p := s.php()
		l.PHP = &p
	}
	return l, nil
}

// totalMB adds the memory limits of every website (trash not counted; WP-CLI runs only for a moment).
func (m *Manager) totalMB() int {
	all, err := m.List()
	if err != nil {
		return 0
	}
	t := 0
	for _, o := range all {
		svcs, _, err := o.limitsOf()
		if err != nil {
			continue
		}
		for _, v := range svcs {
			if v.Service != "cli" {
				t += v.Current
			}
		}
	}
	return t
}

func allowed(v int, list []int) bool {
	for _, x := range list {
		if x == v {
			return true
		}
	}
	return false
}

// SetLimits raises a website's limits, or lowers them back to the standard (never below), and recreates its
// containers with them.
func (m *Manager) SetLimits(ctx context.Context, id string, c LimitChange) error {
	s, err := m.readySite(id)
	if err != nil {
		return err
	}
	svcs, hasPHP, err := s.limitsOf()
	if err != nil {
		return fmt.Errorf("%w: this agent no longer offers the version this website runs", ErrBadInput)
	}
	std := map[string]ServiceRAM{}
	for _, v := range svcs {
		std[v.Service] = v
	}
	ram := map[string]int{}
	for k, v := range s.RAM {
		ram[k] = v
	}
	names := make([]string, 0, len(c.RAM))
	for k := range c.RAM {
		names = append(names, k)
	}
	sort.Strings(names)
	for _, k := range names {
		v, cur := c.RAM[k], std[k]
		switch _, ok := std[k]; {
		case !ok:
			return fmt.Errorf("%w: this website has no service %q", ErrBadInput, k)
		case v == cur.Standard:
			delete(ram, k)
		case v > cur.Standard && allowed(v, RAMChoices):
			ram[k] = v
		default:
			return fmt.Errorf("%w: memory of %s can be the standard %d MB or one of %v MB above it", ErrBadInput, k, cur.Standard, RAMChoices)
		}
	}
	php := s.PHPLimits
	if c.PHP != nil {
		if !hasPHP {
			return fmt.Errorf("%w: this website has no PHP settings", ErrBadInput)
		}
		p := *c.PHP
		for _, f := range []struct {
			key string
			v   int
		}{{"memory_mb", p.Memory}, {"upload_mb", p.Upload}, {"exec_seconds", p.ExecTime}, {"max_input_vars", p.InputVars}} {
			if !allowed(f.v, PHPChoices[f.key]) {
				return fmt.Errorf("%w: %s can be one of %v", ErrBadInput, f.key, PHPChoices[f.key])
			}
		}
		php = nil
		if p != PHPStandard {
			php = &p
		}
	}
	// memory_limit always has room in every container that runs PHP: raising it raises those containers too
	if php != nil {
		for _, v := range svcs {
			if !v.PHP {
				continue
			}
			mem := v.Standard
			if r, ok := ram[v.Service]; ok {
				mem = r
			}
			if n := ramFor(php.Memory, mem); n > mem {
				ram[v.Service] = n
			}
		}
	}
	if len(ram) == 0 {
		ram = nil
	}
	if !m.mu.TryLock() {
		return ErrBusy
	}
	defer m.mu.Unlock()
	next := s
	next.RAM, next.PHPLimits = ram, php
	return m.writeLimits(ctx, next)
}

// writeLimits writes the website's files with its new limits and recreates its containers; on a failure the
// previous files come back and the website is started on them again.
func (m *Manager) writeLimits(ctx context.Context, s Site) error {
	if s.IsNative() {
		return m.nativeLimits(ctx, s)
	}
	dir := m.dir(s.ID)
	cf, err := s.Compose()
	if err != nil {
		return err
	}
	prev := map[string][]byte{}
	for _, f := range []string{"compose.yml", "php.ini", "nginx.conf", "apache.conf", "site.json"} {
		if b, err := os.ReadFile(filepath.Join(dir, f)); err == nil {
			prev[f] = b
		}
	}
	cf = keepImages(cf, string(prev["compose.yml"])) // newer images only through "Update image" (IMG-01)
	next := map[string][]byte{"compose.yml": []byte(cf)}
	if _, ok := prev["php.ini"]; ok {
		next["php.ini"] = []byte(s.PHPIniFile())
	}
	if b, ok := prev["nginx.conf"]; ok {
		next["nginx.conf"] = []byte(s.withNginxRules(s.nginxBody(string(b))))
	}
	if s.apacheMount() != "" {
		next["apache.conf"] = []byte(s.apacheRules())
	}
	putBack := func() {
		for f, b := range prev {
			_ = writeFile(filepath.Join(dir, f), b, 0o644)
		}
	}
	for f, b := range next {
		if err := writeFile(filepath.Join(dir, f), b, 0o644); err != nil {
			putBack()
			return err
		}
	}
	if err := writeSite(dir, s); err != nil {
		putBack()
		return err
	}
	ctx, cancel := context.WithTimeout(ctx, 5*time.Minute) // within the panel's 6 minutes
	defer cancel()
	// php.ini and nginx.conf are read when a container starts: a change of them recreates every container
	args := []string{"up", "-d", "--wait", "--wait-timeout", fmt.Sprint(StartTimeout)}
	if string(prev["php.ini"]) != string(next["php.ini"]) || string(prev["nginx.conf"]) != string(next["nginx.conf"]) ||
		(next["apache.conf"] != nil && string(prev["apache.conf"]) != string(next["apache.conf"])) {
		args = append(args, "--force-recreate")
	}
	if out, err := m.compose(ctx, s.ID, nil, args...); err != nil {
		putBack()
		if out2, err2 := m.compose(ctx, s.ID, nil, "up", "-d", "--force-recreate", "--wait", "--wait-timeout", fmt.Sprint(StartTimeout)); err2 != nil {
			return fmt.Errorf("the website did not start with the new limits (%s), nor with the previous ones: %s", tail(out), tail(out2))
		}
		return fmt.Errorf("the website did not start with the new limits, it runs with the previous ones again: %s", tail(out))
	}
	return nil
}
