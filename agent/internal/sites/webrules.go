// checkMIME parses a content type and its extensions ("tex ltx" or "tex, .ltx").
func checkMIME(typ, exts string) (string, []string, error) {
	typ = strings.ToLower(strings.TrimSpace(typ))
	if !mimeTypeRe.MatchString(typ) {
		return "", nil, fmt.Errorf("%w: %q is not a content type (for example application/x-font-woff)", ErrBadInput, typ)
	}
	seen := map[string]bool{}
	var out []string
	for _, e := range strings.FieldsFunc(strings.ToLower(exts), func(r rune) bool { return r == ' ' || r == ',' || r == '\t' }) {
		e = strings.TrimPrefix(e, ".")
		if !mimeExtRe.MatchString(e) {
			return "", nil, fmt.Errorf("%w: %q is not a file extension", ErrBadInput, e)
		}
		if !seen[e] {
			seen[e] = true
			out = append(out, e)
		}
	}
	if len(out) == 0 || len(out) > 20 {
		return "", nil, fmt.Errorf("%w: give 1 to 20 extensions", ErrBadInput)
	}
	return typ, out, nil
}

// nextWebRules applies an error page or MIME change; ok is false for any other op.
func nextWebRules(s Site, next *Site, c SecurityChange) (bool, error) {
	switch c.Op {
	case "errpage-on", "errpage-off", "mime-add", "mime-remove":
	default:
		return false, nil
	}
	if !s.HasWebServer() {
		return true, fmt.Errorf("%w: this website has no web server of its own for error pages and MIME types", ErrBadInput)
	}
	next.ErrorPages = append([]int(nil), s.ErrorPages...)
	next.MIME = nil
	for _, m := range s.MIME {
		next.MIME = append(next.MIME, MIME{Type: m.Type, Exts: append([]string(nil), m.Exts...)})
	}
	has := func(code int) int {
		for i, x := range next.ErrorPages {
			if x == code {
				return i
			}
		}
		return -1
	}
	switch c.Op {
	case "errpage-on":
		known := false
		for _, x := range ErrorCodes {
			known = known || x == c.Code
		}
		if !known {
			return true, fmt.Errorf("%w: no error page for code %d", ErrBadInput, c.Code)
		}
		if has(c.Code) >= 0 {
			return true, ErrNoChange
		}
		next.ErrorPages = append(next.ErrorPages, c.Code)
		sort.Ints(next.ErrorPages)
	case "errpage-off":
		i := has(c.Code)
		if i < 0 {
			return true, ErrNoChange
		}
		next.ErrorPages = append(next.ErrorPages[:i:i], next.ErrorPages[i+1:]...)
	case "mime-add":
		typ, exts, err := checkMIME(c.Type, c.Exts)
		if err != nil {
			return true, err
		}
		taken := map[string]bool{}
		for _, e := range exts {
			taken[e] = true
		}
		var kept []MIME
		found := false
		for _, m := range next.MIME {
			if m.Type == typ {
				found = true
				for _, e := range m.Exts {
					if !taken[e] {
						exts = append(exts, e)
						taken[e] = true
					}
				}
				continue
			}
			var rest []string // an extension belongs to one type only
			for _, e := range m.Exts {
				if !taken[e] {
					rest = append(rest, e)
				}
			}
			if len(rest) > 0 {
				kept = append(kept, MIME{Type: m.Type, Exts: rest})
			}
		}
		if !found && len(kept) >= MaxMIMETypes {
			return true, fmt.Errorf("%w: at most %d MIME types", ErrBadInput, MaxMIMETypes)
		}
		sort.Strings(exts)
		next.MIME = append(kept, MIME{Type: typ, Exts: exts})
		sort.Slice(next.MIME, func(i, j int) bool { return next.MIME[i].Type < next.MIME[j].Type })
	case "mime-remove":
		i := -1
		for k, m := range next.MIME {
			if m.Type == c.Type {
				i = k
			}
		}
		if i < 0 {
			return true, fmt.Errorf("%w: %s has no MIME rule", ErrBadInput, c.Type)
		}
		next.MIME = append(next.MIME[:i:i], next.MIME[i+1:]...)
	}
	if len(next.ErrorPages) == 0 {
		next.ErrorPages = nil
	}
	if len(next.MIME) == 0 {
		next.MIME = nil
	}
	return true, nil
}

// writeStarterPage writes the page of a code into the website folder unless it is there already.
func (m *Manager) writeStarterPage(s Site, code int) error {
	dir := s.ErrorDir()
	if err := m.Mkdir(s.ID, dir); err != nil && err != ErrExists {
		// the parent of /public/.nostek-errors exists in a Laravel app; anything else is an error
		return err
	}
	p := dir + "/" + strconv.Itoa(code) + ".html"
	if _, err := m.StatFile(s.ID, p); err == nil {
		return nil
	}
	_, err := m.WriteFile(s.ID, p, strings.NewReader(starterPage(code, s.Canonical())), false)
	return err
}
