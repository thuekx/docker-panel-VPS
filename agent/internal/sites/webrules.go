package sites

// Custom error pages and MIME types (SEC-01 wave 2), like cPanel's Error Pages and MIME Types. They live in the
// website's own web server (Nginx or Apache, Docker or native), for the websites that have one: WordPress, plain
// PHP, Laravel and static. The pages are files in the website folder, under /.nostek-errors/, which the File
// Manager edits like any other file; the agent writes a starter page when a code is turned on.

import (
	"fmt"
	"html"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/thuekx/docker-panel-VPS/agent/internal/spec"
)

// ErrorCodes are the codes that can get a page of their own.
var ErrorCodes = []int{400, 401, 403, 404, 500, 502, 503, 504}

const (
	errDir       = ".nostek-errors"
	MaxMIMETypes = 50
	rulesBegin   = "    # nostek-rules begin (error pages and MIME types, SEC-01)"
	rulesEnd     = "    # nostek-rules end"
)

// MIME maps file extensions to a content type.
type MIME struct {
	Type string   `json:"type"`
	Exts []string `json:"exts"`
}

var (
	mimeTypeRe = regexp.MustCompile(`^[a-z0-9][a-z0-9!#&^_.+-]{0,63}/[a-z0-9][a-z0-9!#&^_.+-]{0,126}$`)
	mimeExtRe  = regexp.MustCompile(`^[a-z0-9][a-z0-9_-]{0,15}$`)
)

// HasWebServer is true when the website has its own Nginx or Apache that serves files.
func (s Site) HasWebServer() bool {
	if s.IsReady() || s.IsRuntime() {
		return false
	}
	return s.IsWP() || s.IsLaravel() || s.AppName() == spec.AppStatic || s.AppName() == spec.AppPHP
}

// ErrorDir is the folder of the error pages as the File Manager shows it.
func (s Site) ErrorDir() string {
	if s.IsLaravel() {
		return "/public/" + errDir
	}
	return "/" + errDir
}

func (s Site) hasWebRules() bool { return len(s.ErrorPages) > 0 || len(s.MIME) > 0 }

// nginxRules are the lines of the rules inside the server block ("" when there are none).
func (s Site) nginxRules() string {
	if !s.hasWebRules() {
		return ""
	}
	var b strings.Builder
	b.WriteString(rulesBegin + "\n")
	for _, c := range s.ErrorPages {
		fmt.Fprintf(&b, "    error_page %d /%s/%d.html;\n", c, errDir, c)
	}
	if len(s.ErrorPages) > 0 {
		// ^~ wins over the dot-file deny, so the pages are served
		fmt.Fprintf(&b, "    location ^~ /%s/ { access_log off; }\n", errDir)
	}
	if len(s.MIME) > 0 {
		own := map[string]bool{}
		for _, m := range s.MIME {
			for _, e := range m.Exts {
				own[e] = true
			}
		}
		b.WriteString("    types {\n")
		for _, m := range standardMIME { // the standard map, less the extensions the website maps itself
			var exts []string
			for _, e := range m.Exts {
				if !own[e] {
					exts = append(exts, e)
				}
			}
			if len(exts) > 0 {
				fmt.Fprintf(&b, "        %s %s;\n", m.Type, strings.Join(exts, " "))
			}
		}
		for _, m := range s.MIME {
			fmt.Fprintf(&b, "        %s %s;\n", m.Type, strings.Join(m.Exts, " "))
		}
		b.WriteString("    }\n")
	}
	b.WriteString(rulesEnd + "\n")
	return b.String()
}

// withNginxRules puts the website's rules into its Nginx server block, replacing earlier ones.
func (s Site) withNginxRules(conf string) string {
	if i := strings.Index(conf, rulesBegin); i >= 0 {
		if j := strings.Index(conf[i:], rulesEnd+"\n"); j >= 0 {
			conf = conf[:i] + conf[i+j+len(rulesEnd)+1:]
		}
	}
	r := s.nginxRules()
	if r == "" {
		return conf
	}
	k := strings.LastIndex(conf, "}")
	if k < 0 {
		return conf
	}
	return conf[:k] + r + conf[k:]
}

// apacheMount is the volume line of the Apache rules file, only while there are rules (a mount of a missing
// file would make Docker create a folder in its place).
func (s Site) apacheMount() string {
	if s.Server != "apache" || !s.hasWebRules() {
		return ""
	}
	return "      - ./apache.conf:/etc/apache2/conf-enabled/zz-nostek.conf:ro\n"
}

// apacheRules is the Apache configuration of the rules (zz-nostek.conf).
func (s Site) apacheRules() string {
	var b strings.Builder
	b.WriteString("# Generated by nostek-agent: error pages and MIME types (SEC-01). Do not edit.\n")
	for _, c := range s.ErrorPages {
		fmt.Fprintf(&b, "ErrorDocument %d /%s/%d.html\n", c, errDir, c)
	}
	for _, m := range s.MIME {
		fmt.Fprintf(&b, "AddType %s %s\n", m.Type, "."+strings.Join(m.Exts, " ."))
	}
	return b.String()
}

// errorPageTitles are the starter pages' texts.
