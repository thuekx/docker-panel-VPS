// Composer is the official Composer image; the Laravel image copies its composer binary (APP-01 Laravel).
const Composer = "composer:2@sha256:ca11f643d7791ebdd90a34fc20caf11380d434007ae539a9ea75cd9212e13dca"

// LaravelDockerfile is the recipe of the Laravel image for a PHP version: the pinned official PHP-FPM image of
// that version (the same one WordPress sites use), plus the pdo_mysql extension Laravel needs for MariaDB, unzip
// for Composer, and the binary of the pinned official Composer image. It is built on the server, once per PHP
// version and recipe; nothing else is added.
func LaravelDockerfile(p PHPVersion) string {
	return "# Generated by nostek-agent: Laravel image (official PHP-FPM + pdo_mysql + Composer).\n" +
		"FROM " + Composer + " AS composer\n" +
		"FROM " + p.FPM + "\n" +
		"COPY --from=composer /usr/bin/composer /usr/local/bin/composer\n" +
		"RUN set -eux; \\\n" +
		"    apt-get update; \\\n" +
		"    apt-get install -y --no-install-recommends $PHPIZE_DEPS unzip; \\\n" +
		"    docker-php-ext-install -j\"$(nproc)\" pdo_mysql; \\\n" +
		"    apt-get purge -y --auto-remove $PHPIZE_DEPS; \\\n" +
		"    rm -rf /var/lib/apt/lists/* /tmp/*\n" +
		"ENV COMPOSER_HOME=/tmp/composer COMPOSER_NO_INTERACTION=1\n"
}

// LaravelVersion is one offered Laravel major version and the lowest PHP it runs on.
type LaravelVersion struct {
	Version string
	MinPHP  string
}

// LaravelDefault is the Laravel version preselected in the panel (the newest).
const LaravelDefault = "13"

var laravel = []LaravelVersion{{Version: "13", MinPHP: "8.3"}, {Version: "12", MinPHP: "8.2"}}

// Laravel returns the entry for a Laravel major version.
func Laravel(v string) (LaravelVersion, bool) {
	for _, l := range laravel {
		if l.Version == v {
			return l, true
		}
	}
	return LaravelVersion{}, false
}

// LaravelAll returns the offered Laravel versions, newest first.
func LaravelAll() []LaravelVersion { return append([]LaravelVersion(nil), laravel...) }

// LaravelImage is the local tag of the built Laravel image. It names the PHP version and a hash of the recipe,
// so a new recipe (a new pinned base image) gets a new tag and never reuses an old build.
func LaravelImage(p PHPVersion) string {
	sum := sha256.Sum256([]byte(LaravelDockerfile(p)))
	return "nostek-local/laravel:php" + p.Version + "-" + hex.EncodeToString(sum[:])[:12]
}

